#!/usr/bin/env python3
"""Generate the browser release from a pinned bundle. --check is read-only."""
import argparse
import hashlib
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parent.parent
CATALOG=json.loads((ROOT/'firmware/releases.json').read_text())
RELEASE = {
    'bundle': CATALOG['confirmed']['bundle'],
    'version': CATALOG['confirmed']['version'],
    'legacyBuild': CATALOG['confirmed']['legacyBuild'],
    'date': '2026-11-18',
    'label': 'Hardware-tested by the maintainer',
    'baseVersion': 'Ground Control v3.26',
    'baseHash': 'e1db4815f8cf2983f832493aa8b2085586cb5ea10446e133774bdfc91bca9f52',
    'filename': CATALOG['confirmed']['cardFilename'],
    'features': ['Eight-note MIDI chords on melodic tracks 1–3', 'Live polyphonic recording and step editing', 'Single-file patterns with embedded chord data', 'Locked pattern switching and quiet startup restore', 'DIN MIDI realtime clock priority'],
    'limitations': ['CC automation recording and playback are not included in this release.', 'CV/gate outputs remain monophonic.', 'Save chord edits before leaving a pattern on the module.', 'Back up your card before installing unofficial firmware.'],
}
def generated():
    bundle = json.loads((ROOT / RELEASE['bundle']).read_text())
    assert bundle['version'] == RELEASE['version']
    original=json.loads((ROOT/CATALOG['confirmed']['source']).read_text())
    assert bundle['patches']==original['patches'] and bundle['requires']==original['requires'], 'Public preview diverges from confirmed engineering build'
    bundle['description'] = 'Live polyphonic recording, step editing, single-file patterns, locked switching and quiet startup restore.'
    payload = dict(RELEASE, patchBundle=bundle, bundleHash=hashlib.sha256((ROOT / RELEASE['bundle']).read_bytes()).hexdigest())
    candidate_path=ROOT/CATALOG['candidate']['bundle']
    if candidate_path.exists():
        candidate=json.loads(candidate_path.read_text())
        payload['candidate']={'bundle':CATALOG['candidate']['bundle'],'legacyBuild':CATALOG['candidate']['legacyBuild'],'version':candidate['version'],'date':RELEASE['date'],'label':'Experimental candidate. Hardware validation pending.','baseVersion':RELEASE['baseVersion'],'baseHash':RELEASE['baseHash'],'filename':CATALOG['candidate']['cardFilename'],'features':RELEASE['features']+['Four CC lanes per melodic track, including external CV recording'],'limitations':['This candidate has emulator coverage but has not been tested on the physical module.','Use a backed-up copy of your SD card for testing.','CC recording is step-quantized and limited to four controllers per track.']+RELEASE['limitations'][1:],'patchBundle':candidate,'bundleHash':hashlib.sha256(candidate_path.read_bytes()).hexdigest()}
    return '/* Generated by tools/web_release.py. Do not edit. */\nwindow.GCRelease = ' + json.dumps(payload, separators=(',', ':')) + ';\n'
if __name__ == '__main__':
    parser = argparse.ArgumentParser(); parser.add_argument('--check', action='store_true'); args = parser.parse_args()
    target = ROOT / 'assets/release.js'; output = generated()
    if args.check:
        if not target.exists() or target.read_text() != output: raise SystemExit('Browser release is stale. Run python3 tools/web_release.py')
        print('Browser release matches pinned bundle and metadata.')
    else:
        target.write_text(output); print('Generated', target.relative_to(ROOT))
